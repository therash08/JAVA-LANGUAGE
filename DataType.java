public class DataType {
    public static void main(String[] args) {

        boolean b = true;
        char c = 'a';
        short s = 5484;
        int i = 44488456;
        float f = 10.3f;
        double d  = 34.90;

       
        System.out.println("b = " + b);
        System.out.println("c = "+c);
        System.out.println("s = "+s);
        System.out.println("i = "+i);
        System.out.println("f = "+f);
        System.out.println("d = "+d);
    }
}

